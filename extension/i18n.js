export function getBestLanguage(preferred) {
  if (preferred && preferred in translations) {
    return preferred;
  }
  if (typeof navigator !== "undefined" && navigator.language) {
    const lang = navigator.language.toLowerCase().split("-")[0];
    if (lang in translations) {
      return lang;
    }
  }
  return "en";
}
