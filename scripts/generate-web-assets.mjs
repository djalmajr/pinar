import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative, resolve, sep } from "node:path";

const CONTENT_TYPES = {
  ".css": "text/css; charset=utf-8",
  ".html": "text/html; charset=utf-8",
  ".ico": "image/x-icon",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".png": "image/png",
  ".svg": "image/svg+xml; charset=utf-8",
  ".webp": "image/webp",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
};

const distRoot = resolve(process.cwd(), "apps/web/dist");
const outputPath = resolve(process.cwd(), "src/web-assets.generated.mjs");

function listFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  });
}

if (!statSync(distRoot).isDirectory()) throw new Error(`Web build not found: ${distRoot}`);

const assets = Object.fromEntries(
  listFiles(distRoot).map((filePath) => {
    const requestPath = `/${relative(distRoot, filePath).split(sep).join("/")}`;
    return [
      requestPath,
      {
        contentType: CONTENT_TYPES[extname(filePath)] || "application/octet-stream",
        data: readFileSync(filePath).toString("base64"),
      },
    ];
  }),
);

const output = `// Generated by scripts/generate-web-assets.mjs. Do not edit.\nexport const webAssets = ${JSON.stringify(assets)};\n`;
writeFileSync(outputPath, output, "utf8");
console.log(`Embedded ${Object.keys(assets).length} web assets in ${outputPath}`);
